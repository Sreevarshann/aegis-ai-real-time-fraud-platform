"""Initial AEGIS schema: tenants, users, transactions, predictions, alerts, investigations,
model registry, data quality, pipeline stats, dead letters and audit log.

Design notes
------------
* Every business table carries ``tenant_id`` (FK -> tenants) and every tenant-facing index
  leads with it, so tenant-scoped queries are index-driven and isolation is cheap to enforce.
* ``transactions.transaction_id`` is the idempotency key: replays hit the primary key and
  ``INSERT ... ON CONFLICT DO NOTHING`` turns them into no-ops.
* ``transactions.seq`` is a monotonically increasing cursor for live feeds / pagination.
* Simulation ground-truth lives in its own table and is never read by the scoring path.
* CHECK constraints encode domain rules so bad data cannot be persisted even by a buggy writer.

Revision ID: 0001
Revises:
Create Date: 2026-11-02
"""

from alembic import op

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None

UPGRADE_SQL = """
CREATE TABLE tenants (
    tenant_id   VARCHAR(32) PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users (
    user_id       UUID PRIMARY KEY,
    tenant_id     VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    email         VARCHAR(254) NOT NULL UNIQUE,
    full_name     VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(16)  NOT NULL CHECK (role IN ('admin', 'analyst', 'viewer')),
    is_active     BOOLEAN NOT NULL DEFAULT true,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_users_tenant ON users (tenant_id);

-- Reference data (synthetic KYC / merchant onboarding). Composite keys keep ids tenant-local.
CREATE TABLE customers (
    tenant_id          VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    customer_id        VARCHAR(32) NOT NULL,
    home_country       CHAR(2) NOT NULL,
    registered_devices JSONB NOT NULL,
    account_opened_at  TIMESTAMPTZ NOT NULL,
    avg_ticket_usd     NUMERIC(12, 2) NOT NULL CHECK (avg_ticket_usd > 0),
    PRIMARY KEY (tenant_id, customer_id)
);

CREATE TABLE merchants (
    tenant_id   VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    merchant_id VARCHAR(32) NOT NULL,
    name        VARCHAR(120) NOT NULL,
    category    VARCHAR(32) NOT NULL,
    country     CHAR(2) NOT NULL,
    PRIMARY KEY (tenant_id, merchant_id)
);

CREATE TABLE model_versions (
    model_version_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version            VARCHAR(64) NOT NULL UNIQUE,
    algorithm          VARCHAR(64) NOT NULL,
    artifact_path      TEXT NOT NULL,
    feature_names      JSONB NOT NULL,
    metrics            JSONB NOT NULL,
    training_summary   JSONB NOT NULL,
    decision_threshold DOUBLE PRECISION NOT NULL CHECK (decision_threshold BETWEEN 0 AND 1),
    mlflow_run_id      VARCHAR(64),
    is_active          BOOLEAN NOT NULL DEFAULT false,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- At most one active model at any time.
CREATE UNIQUE INDEX ux_model_versions_single_active ON model_versions (is_active) WHERE is_active;

CREATE TABLE transactions (
    transaction_id    UUID PRIMARY KEY,
    seq               BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
    tenant_id         VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    event_id          UUID NOT NULL,
    schema_version    VARCHAR(8) NOT NULL,
    event_timestamp   TIMESTAMPTZ NOT NULL,
    ingested_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    customer_id       VARCHAR(32) NOT NULL,
    merchant_id       VARCHAR(32) NOT NULL,
    merchant_category VARCHAR(32) NOT NULL,
    amount            NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    currency          CHAR(3) NOT NULL,
    country           CHAR(2) NOT NULL,
    device_id         VARCHAR(64) NOT NULL,
    payment_channel   VARCHAR(24) NOT NULL,
    status            VARCHAR(16) NOT NULL CHECK (status IN ('approved', 'declined', 'pending')),
    is_late           BOOLEAN NOT NULL DEFAULT false,
    payload_hash      CHAR(64) NOT NULL,
    kafka_partition   INTEGER,
    kafka_offset      BIGINT,
    FOREIGN KEY (tenant_id, customer_id) REFERENCES customers (tenant_id, customer_id),
    FOREIGN KEY (tenant_id, merchant_id) REFERENCES merchants (tenant_id, merchant_id)
);
-- Live feed / recent activity per tenant.
CREATE INDEX ix_transactions_tenant_seq ON transactions (tenant_id, seq DESC);
-- Time-window analytics (hourly volume, dbt incremental scans).
CREATE INDEX ix_transactions_tenant_event_ts ON transactions (tenant_id, event_timestamp DESC);
-- Investigation evidence: customer history, device and merchant lookups.
CREATE INDEX ix_transactions_customer ON transactions (tenant_id, customer_id, event_timestamp DESC);
CREATE INDEX ix_transactions_device ON transactions (tenant_id, device_id, event_timestamp DESC);
CREATE INDEX ix_transactions_merchant ON transactions (tenant_id, merchant_id, event_timestamp DESC);

CREATE TABLE simulation_labels (
    transaction_id UUID PRIMARY KEY REFERENCES transactions(transaction_id) ON DELETE CASCADE,
    tenant_id      VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    is_fraud       BOOLEAN NOT NULL,
    scenario       VARCHAR(32) NOT NULL
);
COMMENT ON TABLE simulation_labels IS
    'Synthetic ground truth for offline evaluation only. Never read by the scoring path.';

CREATE TABLE risk_predictions (
    prediction_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id     UUID NOT NULL UNIQUE REFERENCES transactions(transaction_id) ON DELETE CASCADE,
    tenant_id          VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    model_version_id   INTEGER NOT NULL REFERENCES model_versions(model_version_id),
    risk_score         INTEGER NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    probability        DOUBLE PRECISION NOT NULL CHECK (probability BETWEEN 0 AND 1),
    risk_category      VARCHAR(16) NOT NULL CHECK (risk_category IN ('low', 'medium', 'high', 'critical')),
    features           JSONB NOT NULL,
    explanation        JSONB NOT NULL,
    scoring_latency_ms DOUBLE PRECISION NOT NULL,
    scored_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_predictions_tenant_scored ON risk_predictions (tenant_id, scored_at DESC);
CREATE INDEX ix_predictions_model ON risk_predictions (model_version_id, scored_at DESC);

CREATE TABLE risk_alerts (
    alert_id       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id      VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    transaction_id UUID NOT NULL UNIQUE REFERENCES transactions(transaction_id) ON DELETE CASCADE,
    prediction_id  BIGINT NOT NULL REFERENCES risk_predictions(prediction_id) ON DELETE CASCADE,
    severity       VARCHAR(16) NOT NULL CHECK (severity IN ('medium', 'high', 'critical')),
    status         VARCHAR(24) NOT NULL DEFAULT 'open'
                   CHECK (status IN ('open', 'investigating', 'escalated', 'dismissed', 'confirmed_fraud')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Analyst queue: open alerts per tenant, newest first.
CREATE INDEX ix_alerts_tenant_status ON risk_alerts (tenant_id, status, created_at DESC);

CREATE TABLE investigations (
    investigation_id UUID PRIMARY KEY,
    tenant_id        VARCHAR(32) NOT NULL REFERENCES tenants(tenant_id),
    alert_id         BIGINT REFERENCES risk_alerts(alert_id) ON DELETE SET NULL,
    transaction_id   UUID NOT NULL REFERENCES transactions(transaction_id) ON DELETE CASCADE,
    created_by       UUID NOT NULL REFERENCES users(user_id),
    engine           VARCHAR(16) NOT NULL CHECK (engine IN ('deterministic', 'ollama')),
    llm_model        VARCHAR(64),
    priority         VARCHAR(8) NOT NULL CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    report           JSONB NOT NULL,
    review_status    VARCHAR(24) NOT NULL DEFAULT 'pending_review'
                     CHECK (review_status IN ('pending_review', 'in_review', 'escalated',
                                              'closed_fraud', 'closed_legitimate')),
    reviewer_notes   TEXT,
    duration_ms      DOUBLE PRECISION NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_investigations_tenant_created ON investigations (tenant_id, created_at DESC);
CREATE INDEX ix_investigations_transaction ON investigations (tenant_id, transaction_id);

CREATE TABLE dead_letter_events (
    dead_letter_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id        VARCHAR(32),
    reason           VARCHAR(48) NOT NULL,
    error_detail     TEXT NOT NULL,
    raw_payload      TEXT NOT NULL,
    source_topic     VARCHAR(128) NOT NULL,
    source_partition INTEGER,
    source_offset    BIGINT,
    received_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Quarantine can be replayed or audited by source position; never double-quarantine a message.
CREATE UNIQUE INDEX ux_dead_letter_source ON dead_letter_events (source_topic, source_partition, source_offset);
CREATE INDEX ix_dead_letter_received ON dead_letter_events (received_at DESC);

CREATE TABLE data_quality_results (
    result_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id         UUID NOT NULL,
    tenant_id      VARCHAR(32) REFERENCES tenants(tenant_id),
    check_name     VARCHAR(64) NOT NULL,
    dimension      VARCHAR(24) NOT NULL,
    status         VARCHAR(8) NOT NULL CHECK (status IN ('pass', 'warn', 'fail')),
    observed_value DOUBLE PRECISION,
    threshold      DOUBLE PRECISION,
    details        JSONB NOT NULL,
    checked_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_dq_checked ON data_quality_results (checked_at DESC);
CREATE INDEX ix_dq_run ON data_quality_results (run_id);

CREATE TABLE pipeline_stats (
    stat_id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    component         VARCHAR(48) NOT NULL,
    instance_id       VARCHAR(64) NOT NULL,
    window_started_at TIMESTAMPTZ NOT NULL,
    window_ended_at   TIMESTAMPTZ NOT NULL,
    consumed          INTEGER NOT NULL,
    persisted         INTEGER NOT NULL,
    duplicates        INTEGER NOT NULL,
    dead_lettered     INTEGER NOT NULL,
    late              INTEGER NOT NULL,
    errors            INTEGER NOT NULL,
    consumer_lag      BIGINT,
    avg_processing_ms DOUBLE PRECISION
);
CREATE INDEX ix_pipeline_stats_window ON pipeline_stats (window_ended_at DESC);

CREATE TABLE transformation_runs (
    run_row_id       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    invocation_id    VARCHAR(64) NOT NULL,
    node_id          VARCHAR(256) NOT NULL,
    resource_type    VARCHAR(16) NOT NULL,
    status           VARCHAR(16) NOT NULL,
    execution_time_s DOUBLE PRECISION,
    rows_affected    BIGINT,
    message          TEXT,
    completed_at     TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_transformation_runs_completed ON transformation_runs (completed_at DESC);

CREATE TABLE audit_events (
    audit_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id     VARCHAR(32) REFERENCES tenants(tenant_id),
    actor_user_id UUID REFERENCES users(user_id),
    action        VARCHAR(64) NOT NULL,
    entity_type   VARCHAR(32) NOT NULL,
    entity_id     VARCHAR(64),
    details       JSONB NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_tenant_created ON audit_events (tenant_id, created_at DESC);
"""

DOWNGRADE_SQL = """
DROP TABLE IF EXISTS audit_events, transformation_runs, pipeline_stats, data_quality_results,
    dead_letter_events, investigations, risk_alerts, risk_predictions, simulation_labels,
    transactions, model_versions, merchants, customers, users, tenants CASCADE;
"""


def upgrade() -> None:
    op.execute(UPGRADE_SQL)


def downgrade() -> None:
    op.execute(DOWNGRADE_SQL)
